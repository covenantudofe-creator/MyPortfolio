import { useEffect, useRef, useState } from 'react';
import { Link } from 'react-router-dom';
import { ArrowUpRight, Bot, MessageCircle, Send, X } from 'lucide-react';
import { assistantKnowledge, assistantSuggestedQuestions } from '../data/assistantKnowledge.js';
import { answerPortfolioQuestion } from '../utils/portfolioAssistant.js';

function renderAssistantText(text, role) {
  const email = assistantKnowledge.contact.email;
  if (role !== 'assistant' || !text.includes(email)) return text;
  return text.split(email).flatMap((part, index, pieces) => index === pieces.length - 1
    ? [part]
    : [part, <a className="assistant-inline-link" href={`mailto:${email}`} key={`email-${index}`}>{email}</a>]);
}

const initialMessage = {
  role: 'assistant',
  topic: 'welcome',
  text: 'Hello, I’m the portfolio assistant. Ask me about Godscovenant’s software projects, technical skills, engineering contributions, education, résumé, or contact details.',
};

export default function PortfolioAssistant() {
  const [open, setOpen] = useState(false);
  const [messages, setMessages] = useState([initialMessage]);
  const [question, setQuestion] = useState('');
  const [unread, setUnread] = useState(false);
  const listRef = useRef(null);
  const inputRef = useRef(null);

  useEffect(() => {
    if (open) {
      listRef.current?.scrollTo({ top: listRef.current.scrollHeight, behavior: 'smooth' });
      inputRef.current?.focus();
      setUnread(false);
    }
  }, [open, messages]);

  function sendMessage(event, suggestedQuestion = '') {
    event?.preventDefault();
    const text = (suggestedQuestion || question).trim();
    if (!text) return;
    const previousTopic = [...messages].reverse().find((message) => message.role === 'assistant')?.topic || '';
    const response = answerPortfolioQuestion(text, previousTopic);
    setMessages((current) => [...current, { role: 'visitor', text }, { role: 'assistant', ...response }]);
    setQuestion('');
    if (!open) setUnread(true);
  }

  return (
    <aside className="portfolio-assistant" aria-label="Portfolio assistant">
      {open && (
        <section className="assistant-panel" role="dialog" aria-modal="false" aria-labelledby="assistant-title">
          <header className="assistant-header">
            <span className="assistant-avatar"><Bot size={18} aria-hidden="true" /></span>
            <div><h2 id="assistant-title">Portfolio assistant</h2><p>Answers from this portfolio</p></div>
            <button type="button" className="assistant-close" onClick={() => setOpen(false)} aria-label="Close portfolio assistant"><X size={18} /></button>
          </header>
          <div className="assistant-messages" ref={listRef} role="log" aria-live="polite" aria-relevant="additions text">
            {messages.map((message, index) => (
              <div className={`assistant-message assistant-message-${message.role}`} key={`${index}-${message.text}`}>
                <p>{renderAssistantText(message.text, message.role)}</p>
                {message.links?.length > 0 && <div className="assistant-links">{message.links.map((link) => link.href ? <a key={`${link.href}-${link.label}`} href={link.href} download={link.download || undefined} target={/^https?:\/\//.test(link.href) ? '_blank' : undefined} rel={/^https?:\/\//.test(link.href) ? 'noopener noreferrer' : undefined}>{link.label}<ArrowUpRight size={13} aria-hidden="true" /></a> : <Link key={`${link.to}-${link.label}`} to={link.to} onClick={() => setOpen(false)}>{link.label}<ArrowUpRight size={13} aria-hidden="true" /></Link>)}</div>}
              </div>
            ))}
          </div>
          <div className="assistant-prompts" aria-label="Suggested questions">
            {messages.length === 1 && assistantSuggestedQuestions.map((prompt) => <button type="button" key={prompt} onClick={() => sendMessage(null, prompt)}>{prompt}</button>)}
          </div>
          <form className="assistant-form" onSubmit={sendMessage}>
            <label className="sr-only" htmlFor="assistant-question">Ask a question about this portfolio</label>
            <input id="assistant-question" ref={inputRef} value={question} onChange={(event) => setQuestion(event.target.value)} placeholder="Ask about the portfolio…" autoComplete="off" />
            <button type="submit" aria-label="Send question" disabled={!question.trim()}><Send size={17} /></button>
          </form>
          <p className="assistant-note">Replies use portfolio information; they are not generated by a live AI service.</p>
        </section>
      )}
      <button type="button" className="assistant-launcher" onClick={() => setOpen((value) => !value)} aria-expanded={open} aria-label={open ? 'Close portfolio assistant' : 'Ask the portfolio assistant'}>
        {open ? <X size={21} /> : <><MessageCircle size={21} /><span>Ask me</span></>}
        {unread && <span className="assistant-unread" aria-label="New response" />}
      </button>
    </aside>
  );
}
